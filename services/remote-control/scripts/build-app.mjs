// Builds KerfDesk Remote (ADR-582) from services/remote-control/app:
//   public/app/*                        installable phone app served by the Worker at /app/
//   electron/mcp/workspace-app-ui.ts    single-file MCP Apps resource (ui://kerfdesk/workspace/v6.html)
// `--check` rebuilds in memory and fails when a committed output is stale.
import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { build } from 'esbuild';
import { appShellVersion } from './app-shell-version.mjs';

const check = process.argv.includes('--check');
if (process.argv.slice(2).some((value) => value !== '--check'))
  throw new Error('Use build-app.mjs with no arguments or --check.');
const root = new URL('../', import.meta.url);
const at = (path) => new URL(path, root);

const shared = {
  bundle: true,
  minify: true,
  write: false,
  target: ['es2020', 'safari15'],
  jsx: 'automatic',
  legalComments: 'none',
  charset: 'utf8',
  define: { 'process.env.NODE_ENV': '"production"' },
  logLevel: 'warning',
};

async function bundle(entry, format) {
  const result = await build({
    ...shared,
    entryPoints: [at(`app/src/${entry}`).pathname.replace(/^\/([A-Za-z]:)/, '$1')],
    format,
    outdir: 'out',
    entryNames: 'app',
  });
  const js = result.outputFiles.find((file) => file.path.endsWith('.js'))?.text ?? '';
  const css = result.outputFiles.find((file) => file.path.endsWith('.css'))?.text ?? '';
  return { js, css };
}

const phone = await bundle('entry-phone.tsx', 'esm');
const mcp = await bundle('entry-mcp.tsx', 'iife');
const copies = ['index.html', 'manifest.webmanifest', 'icon.svg', 'icon-maskable.svg'];
const versionFiles = [
  'app/static/sw.js',
  ...copies.map((name) => `app/static/${name}`),
  ...['icon-192.png', 'icon-512.png', 'icon-maskable-512.png'].map((name) => `public/app/${name}`),
];
const shellFiles = new Map(
  await Promise.all(versionFiles.map(async (name) => [name, await readFile(at(name))])),
);
const version = appShellVersion(phone, shellFiles);
const sw = shellFiles.get('app/static/sw.js').toString('utf8').replace('__APP_VERSION__', version);
const script = mcp.js.replace(/<\/(script)/gi, '<\\/$1');
const style = mcp.css.replace(/<\/(style)/gi, '<\\/$1');
const html = `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>KerfDesk</title><style>${style}</style></head><body><div id="root"></div><script>${script}</script></body></html>`;
const module = `/** Generated by services/remote-control/scripts/build-app.mjs from app/src. Run pnpm build:app; do not edit. */\nexport const KERFDESK_WORKSPACE_APP_URI = 'ui://kerfdesk/workspace/v6.html';\nexport const KERFDESK_WORKSPACE_APP_HTML: string = ${JSON.stringify(html)};\n`;

const outputs = [
  ['public/app/app.js', phone.js],
  ['public/app/app.css', phone.css],
  ['public/app/sw.js', sw],
  ['../../electron/mcp/workspace-app-ui.ts', module],
];

if (check) {
  const stale = [];
  for (const [path, content] of outputs)
    if ((await readFile(at(path), 'utf8').catch(() => '')) !== content) stale.push(path);
  for (const name of copies)
    if (
      (await readFile(at(`public/app/${name}`), 'utf8').catch(() => '')) !==
      (await readFile(at(`app/static/${name}`), 'utf8'))
    )
      stale.push(`public/app/${name}`);
  if (stale.length > 0)
    throw new Error(`KerfDesk Remote build is stale: ${stale.join(', ')}. Run pnpm build:app.`);
  console.log('KerfDesk Remote app: current.');
} else {
  await mkdir(at('public/app/'), { recursive: true });
  for (const [path, content] of outputs) await writeFile(at(path), content);
  for (const name of copies) await copyFile(at(`app/static/${name}`), at(`public/app/${name}`));
  console.log(
    `KerfDesk Remote app: built ${version} (phone ${(phone.js.length / 1024).toFixed(0)} KiB, MCP ${(html.length / 1024).toFixed(0)} KiB).`,
  );
}
