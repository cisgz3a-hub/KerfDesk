export const PUBLISHED_EC_ROWS: readonly PublishedEcRow[] = EC_TABLE.trim()
  .split(/\s*[|\n]\s*/)
  .map(parseEcRow);

function parseEcRow(entry: string): PublishedEcRow {
  const [key = '', total = '', ecc = '', group1 = '', group2 = '0x0'] = entry.split(' ');
  const [version = '', level = ''] = key.split('-');
  const [blocks1 = '', data1 = ''] = group1.split('x');
  const [blocks2 = '', data2 = ''] = group2.split('x');
  return {
    version: Number(version),
    level: level as PublishedEcRow['level'],
    dataCodewords: Number(total),
    eccPerBlock: Number(ecc),
    group1Blocks: Number(blocks1),
    group1Data: Number(data1),
    group2Blocks: Number(blocks2),
    group2Data: Number(data2),
  };
}

export function publishedEcRow(version: number, level: PublishedEcRow['level']): PublishedEcRow {
  const row = PUBLISHED_EC_ROWS.find(
    (candidate) => candidate.version === version && candidate.level === level,
  );
  if (row === undefined) throw new Error(`No published EC row for ${version}-${level}`);
  return row;
}

